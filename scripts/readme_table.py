"""Write the README stress answer and table from results/scenarios.json, so no README number is hand-typed.

Run after scripts/run_all.py:  python3 scripts/readme_table.py          (rewrite README block)
                               python3 scripts/readme_table.py --check  (fail if README is stale)
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
START, END = "<!-- stress-table:start -->", "<!-- stress-table:end -->"
SHOCKS = (-20.0, -40.0, -60.0)


def rate(value):
    return "unbounded" if value is None else f"{value:.3f}%"


def months(value):
    return "more than 24" if value is None else str(value)


def cost(value):
    return "n/a" if value is None else f"${value:,.0f}m"


def render(result=None):
    result = result or json.loads((ROOT / "results/scenarios.json").read_text())
    inputs = result["inputs"]
    rows = result["btc_shock_sensitivity"]

    def pick(shock, form, multiplier=1.0):
        return next(r for r in rows if r["btc_shock_pct"] == shock and r["form"] == form
                    and r["assumed_slope_multiplier"] == multiplier)

    lead = pick(-40.0, "log")
    lo, hi = pick(-40.0, "log", 0.5), pick(-40.0, "log", 1.5)
    btc0 = inputs["btc0"]
    lines = [
        START,
        f"**BTC -40% answer.** If BTC falls 40% from ${btc0:,.0f} to ${btc0 * 0.6:,.0f} and stays there, the "
        f"log-spread model needs a {rate(lead['required_rate_pct'])} dividend rate for STRC to price at $100 "
        f"({rate(lo['required_rate_pct'])} to {rate(hi['required_rate_pct'])} across assumed slope multipliers "
        f"0.5x to 1.5x). The modeled price falls from ${inputs['strc_price0']:.2f} to ${lead['start_price']:.2f}, "
        f"and the stated tiers take {months(lead['months_to_par_band'])} months to lift the rate from "
        f"{inputs['rate0_pct']:.2f}% until the price is back in the $99 band. At the required rate, dividends on "
        f"${inputs['notional_usd'] / 1e9:,.2f}bn notional cost {cost(lead['annual_cost_at_required_usd_m'])} a "
        "year. These are assumed stresses, not forecasts.",
        "",
        "| BTC move | Spread form | Required rate, 1x slope | Range, 0.5x to 1.5x slope | Price after shock "
        "| Months to $99 band | Annual dividend cost at required rate |",
        "|---|---|--:|--:|--:|--:|--:|",
    ]
    for shock in SHOCKS:
        for form in ("log", "distance"):
            r, a, b = pick(shock, form), pick(shock, form, 0.5), pick(shock, form, 1.5)
            lines.append(f"| {shock:.0f}% | {form} | {rate(r['required_rate_pct'])} | "
                         f"{rate(a['required_rate_pct'])} to {rate(b['required_rate_pct'])} | "
                         f"${r['start_price']:.2f} | {months(r['months_to_par_band'])} | "
                         f"{cost(r['annual_cost_at_required_usd_m'])} |")
    lines += ["",
              f"Source: `results/scenarios.json` (`btc_shock_sensitivity`), stated-tier policy, 24-month horizon, "
              f"SOFR {inputs['sofr0_pct']:.2f}% held flat, cutoff {inputs['as_of']}. Generated by "
              "`scripts/readme_table.py`.",
              END]
    return "\n".join(lines)


def updated(text, block):
    head, sep, rest = text.partition(START)
    _, sep2, tail = rest.partition(END)
    if not (sep and sep2):
        raise SystemExit(f"README.md is missing the {START} ... {END} markers")
    return head + block + tail


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the README block differs from results")
    args = parser.parse_args()
    text = README.read_text()
    new = updated(text, render())
    if args.check:
        if new != text:
            raise SystemExit("README stress table is stale; run python3 scripts/readme_table.py")
        print("README stress table matches results/scenarios.json")
    elif new != text:
        README.write_text(new)
        print("Updated README stress table from results/scenarios.json")
    else:
        print("README stress table already matches results/scenarios.json")


if __name__ == "__main__":
    main()
